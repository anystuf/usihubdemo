let language = "en";

export function initLanguage() {
  try {
    language = localStorage.getItem(languageKey) === "vi" ? "vi" : "en";
  } catch {
    language = "en";
  }
  document.documentElement.lang = language;
  return language;
}

export function getLanguage() {
  return language;
}

export function translate(value) {
  return language === "vi" ? (translations[value] || value) : value;
}

export function localizePage(root = document) {
  if (language !== "vi") return;
  const walker = document.createTreeWalker(root.body || root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    const value = node.nodeValue.trim();
    if (!value || !translations[value]) return;
    node.nodeValue = node.nodeValue.replace(value, translations[value]);
  });
  root.querySelectorAll("[placeholder],[title],[aria-label]").forEach((element) => {
    ["placeholder", "title", "aria-label"].forEach((attribute) => {
      const value = element.getAttribute(attribute);
      if (value && translations[value]) element.setAttribute(attribute, translations[value]);
    });
  });
}

export function setLanguage(nextLanguage) {
  language = nextLanguage === "vi" ? "vi" : "en";
  try {
    localStorage.setItem(languageKey, language);
  } catch {}
  document.documentElement.lang = language;
  window.dispatchEvent(new CustomEvent("languageChanged"));
}
